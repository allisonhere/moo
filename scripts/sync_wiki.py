#!/usr/bin/env python3
"""Mirror docs/next into a checkout of the GitHub wiki.

    python3 scripts/sync_wiki.py --wiki PATH           write the mirror
    python3 scripts/sync_wiki.py --wiki PATH --check   exit 1 if the wiki is out of date

docs/next stays the one place docs are written, so a page added or edited there reaches the wiki on
the next run. Pages written here carry MARKER. The script never overwrites a page without it (the
hand-written moo pages) and only deletes pages that still carry it.

The upstream text is Herdr's (Apache-2.0), so each page says so and says what changed.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs/next/website/src/content/docs"
MARKER = "<!-- generated by scripts/sync_wiki.py; edit docs/next, not this page -->"
UPSTREAM = "https://herdr.dev"
REPO = "https://github.com/allisonhere/moo"
LOGO = f"{REPO.replace('github.com', 'raw.githubusercontent.com')}/master/assets/moo-logo.png"

# docs/next/.../index.mdx is the Astro landing page; the wiki gets a generated index instead.
SKIP = {"index"}
# Pages that are moo's own, not Herdr's: no upstream attribution.
OWN = {"moo": "Fork-guide"}
FENCE = re.compile(r"^\s*(```|~~~)")


def page_name(slug: str) -> str:
    return OWN.get(slug) or f"Docs-{slug}"


def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    match = re.match(r"---\n(.*?)\n---\n?", text, re.S)
    if not match:
        return {}, text
    meta = {}
    for line in match.group(1).splitlines():
        key, sep, value = line.partition(":")
        if sep and value.strip() and not line.startswith((" ", "\t")):
            meta[key.strip()] = value.strip().strip("\"'")
    return meta, text[match.end():]


def _aside(lines: list[str]) -> list[str]:
    """Rewrite Starlight `:::note ... :::` blocks as blockquotes."""
    out, quote = [], False
    for line in lines:
        opening = re.match(r"^:::(\w+)(?:\[(.*?)\])?\s*$", line)
        if opening and not quote:
            kind, title = opening.group(1).capitalize(), opening.group(2)
            out.append(f"> **{title or kind}**")
            quote = True
        elif quote and line.strip() == ":::":
            quote = False
        elif quote:
            out.append(f"> {line}" if line.strip() else ">")
        else:
            out.append(line)
    return out


def _prose(text: str, slug: str, slugs: set[str]) -> str:
    text = re.sub(r"^import .*\n", "", text, flags=re.M)
    text = "\n".join(_aside(text.split("\n")))
    text = text.replace(
        "<ConfigReference />",
        f"_The filterable key list is rendered on [herdr.dev]({UPSTREAM}/docs/{slug}/)._",
    )
    text = re.sub(r"<[A-Z]\w*\b[^>]*/>\n?", "", text)
    text = re.sub(
        r"<div[^>]*>(?:(?!</div>).)*?<img(?:(?!</div>).)*</div>",
        f"_Screenshots are on the [original page]({UPSTREAM}/docs/{slug}/)._",
        text,
        flags=re.S,
    )

    def docs_link(match: re.Match) -> str:
        target, anchor = match.group(1), match.group(2) or ""
        if target in slugs:
            return f"]({page_name(target)}{anchor})"
        return f"]({UPSTREAM}/docs/{target}/{anchor})"

    text = re.sub(r"\]\(/docs/([a-z0-9-]+)/?(#[^)\s]*)?\)", docs_link, text)
    text = re.sub(r"\]\(/docs/?\)", "](Documentation)", text)
    return re.sub(r"\]\((/(?!/)[^)\s]*)\)", rf"]({UPSTREAM}\1)", text)


def convert(body: str, slug: str, slugs: set[str]) -> str:
    """Convert MDX to wiki markdown, leaving fenced code exactly as written."""
    out, prose, in_fence = [], [], False
    for line in body.split("\n"):
        if FENCE.match(line):
            if not in_fence and prose:
                out.append(_prose("\n".join(prose), slug, slugs))
                prose = []
            in_fence = not in_fence
            out.append(line)
        elif in_fence:
            out.append(line)
        else:
            prose.append(line)
    if prose:
        out.append(_prose("\n".join(prose), slug, slugs))
    return "\n".join(out)


def _chrome() -> str:
    return (
        f'<a href="Home"><img src="{LOGO}" alt="moo" width="40" align="left" /></a> '
        '<strong>moo wiki</strong> · <a href="Home">Home</a> · <a href="Documentation">Documentation</a>'
    )


def _banner(slug: str) -> str:
    return (
        f"> **Adapted from [Herdr's documentation]({UPSTREAM}/docs/{slug}/)** "
        f"(Apache-2.0, © the Herdr authors; see the [LICENSE]({REPO}/blob/master/LICENSE)). "
        "Changed from the original: converted to wiki markdown, links rewritten, and moo's "
        "additions included. moo uses `moo` where this page says `herdr`, `MOO_*` for `HERDR_*` "
        "and `~/.config/moo` for `~/.config/herdr`; to install moo see [Install](Install)."
    )


def render_page(slug: str, meta: dict[str, str], body: str, slugs: set[str]) -> str:
    title = meta.get("title", slug)
    parts = [MARKER, "", _chrome(), ""]
    if slug not in OWN:
        parts += [_banner(slug), ""]
    parts += [f"# {title}", ""]
    if meta.get("description"):
        parts += [f"_{meta['description']}_", ""]
    parts += [convert(body, slug, slugs).strip(), "", "---", ""]
    parts.append(f"_Source: `docs/next/website/src/content/docs/{slug}.mdx`. Edit that file; this page is regenerated._")
    return "\n".join(parts) + "\n"


def collect(docs: Path) -> dict[str, tuple[dict[str, str], str]]:
    pages = {}
    for path in sorted(docs.glob("*.mdx")):
        if path.stem not in SKIP:
            pages[path.stem] = split_frontmatter(path.read_text())
    return pages


def render_index(pages: dict[str, tuple[dict[str, str], str]]) -> str:
    rows = [
        f"- [{meta.get('title', slug)}]({page_name(slug)})"
        + (f": {meta['description']}" if meta.get("description") else "")
        for slug, (meta, _) in pages.items()
    ]
    return "\n".join(
        [MARKER, "", _chrome(), "", "# Documentation", "",
         "Generated from the repo's docs. Most pages are Herdr's documentation, adapted for moo; "
         "see the note at the top of each page.", "", *rows, ""]
    )


def render_sidebar(pages: dict, hand_written: list[str]) -> str:
    own = [f"- [{name.replace('-', ' ')}]({name})" for name in hand_written]
    ref = [f"- [{meta.get('title', slug)}]({page_name(slug)})" for slug, (meta, _) in pages.items()]
    return "\n".join([MARKER, "", "**[moo](Home)**", "", *own, "", "**Documentation**", "", *ref, ""])


def build(docs: Path, wiki: Path) -> dict[str, str]:
    """The generated files, by file name."""
    pages = collect(docs)
    slugs = set(pages)
    files = {
        f"{page_name(slug)}.md": render_page(slug, meta, body, slugs)
        for slug, (meta, body) in pages.items()
    }
    files["Documentation.md"] = render_index(pages)
    hand_written = sorted(
        path.stem
        for path in wiki.glob("*.md")
        if not path.name.startswith("_")
        and path.name not in files
        and MARKER not in path.read_text()
        and path.stem != "Home"
    )
    files["_Sidebar.md"] = render_sidebar(pages, hand_written)
    return files


def sync(docs: Path, wiki: Path, check: bool = False) -> list[str]:
    """Write (or, with check, only report) the changes; returns what changed."""
    files = build(docs, wiki)
    changes = []
    for name, content in files.items():
        target = wiki / name
        if target.exists():
            current = target.read_text()
            if MARKER not in current:
                raise SystemExit(f"refusing to overwrite hand-written page {name}")
            if current == content:
                continue
        changes.append(name)
        if not check:
            target.write_text(content)
    for stale in wiki.glob("*.md"):
        if stale.name not in files and MARKER in stale.read_text():
            changes.append(f"{stale.name} (removed)")
            if not check:
                stale.unlink()
    return changes


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--wiki", required=True, type=Path, help="path to a checkout of the wiki")
    parser.add_argument("--docs", type=Path, default=DOCS)
    parser.add_argument("--check", action="store_true", help="exit 1 if the wiki is out of date")
    args = parser.parse_args(argv)
    changes = sync(args.docs, args.wiki, args.check)
    for change in changes:
        print(("would change " if args.check else "wrote ") + change)
    if not changes:
        print("wiki is up to date")
    return 1 if (changes and args.check) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
