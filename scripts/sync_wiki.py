#!/usr/bin/env python3
"""Mirror docs/next into a checkout of the GitHub wiki.

    python3 scripts/sync_wiki.py --wiki PATH           write the mirror
    python3 scripts/sync_wiki.py --wiki PATH --check   exit 1 if the wiki is out of date

docs/next stays the one place docs are written, so a page added or edited there reaches the wiki on
the next run. Pages written here carry MARKER. The script never overwrites a page without it (the
hand-written moo pages) and only deletes pages that still carry it.

The upstream text is Herdr's (Apache-2.0), so each page says so and says what changed.
"""

import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs/next/website/src/content/docs"
MARKER = "<!-- generated by scripts/sync_wiki.py; edit docs/next, not this page -->"
UPSTREAM = "https://herdr.dev"
REPO = "https://github.com/allisonhere/moo"
LOGO = f"{REPO.replace('github.com', 'raw.githubusercontent.com')}/master/assets/moo-logo.png"

# docs/next/.../index.mdx is the Astro landing page; the wiki gets a generated index instead.
SKIP = {"index"}
# Pages that are moo's own, not Herdr's: no upstream attribution.
OWN = {"moo": "Fork-guide"}
FENCE = re.compile(r"^\s*(```|~~~)")

# The name moo gives the things upstream calls herdr. Only code (fences and inline code) is rewritten,
# and only where the thing is a command or a path moo really uses; prose, URLs, package names
# (`brew install herdr`), the plugin manifest name and the `ui.toast.herdr` config key stay as upstream wrote them.
PATHS = [
    ("~/.config/herdr", "~/.config/moo"),
    ("~/.local/state/herdr", "~/.local/state/moo"),
    ("%APPDATA%\\herdr", "%APPDATA%\\moo"),
    ("~/.local/bin/herdr", "~/.local/bin/moo"),
    ("/.zfunc/_herdr", "/.zfunc/_moo"),
    ("herdr.exe", "moo.exe"),
    ("herdr-client.sock", "moo-client.sock"),
    ("herdr.sock", "moo.sock"),
]
# `herdr` where it starts a command: a line, a span, or after `$(`, `(`, `|`, `;`, `&&`, `||` or a `$ ` prompt.
COMMAND = re.compile(r"(^\s*(?:\$\s+)?|\$\(\s*|\(\s*|[|;]\s*|&&\s*|\|\|\s*)herdr((?:\s+[a-z][a-z0-9-]*){0,3})(?=\s|\)|$)")
# Code that starts with `herdr` but is not a moo command, found with --verify, so it stays as written:
# upstream commands moo lacks, and quoted messages (`herdr not found in mise tool registry`).
UPSTREAM_ONLY: set[tuple[str, ...]] = {("not",)}
URL = re.compile(r"(https?://\S+)")


def page_name(slug: str) -> str:
    return OWN.get(slug) or f"Docs-{slug}"


def _is_upstream_only(words: list[str]) -> bool:
    return any(words[: len(prefix)] == list(prefix) for prefix in UPSTREAM_ONLY)


def _command(match: re.Match) -> str:
    words = match.group(2).split()
    return match.group(1) + ("herdr" if _is_upstream_only(words) else "moo") + match.group(2)


def rewrite_code(text: str) -> str:
    """`herdr` becomes `moo` in the commands and paths of one line of code; URLs are left alone."""
    parts = URL.split(text)
    for index in range(0, len(parts), 2):
        part = parts[index]
        for old, new in PATHS:
            part = part.replace(old, new)
        parts[index] = COMMAND.sub(_command, part)
    return "".join(parts)


def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    match = re.match(r"---\n(.*?)\n---\n?", text, re.S)
    if not match:
        return {}, text
    meta = {}
    for line in match.group(1).splitlines():
        key, sep, value = line.partition(":")
        if sep and value.strip() and not line.startswith((" ", "\t")):
            meta[key.strip()] = value.strip().strip("\"'")
    return meta, text[match.end():]


def _aside(lines: list[str]) -> list[str]:
    """Rewrite Starlight `:::note ... :::` blocks as blockquotes."""
    out, quote = [], False
    for line in lines:
        opening = re.match(r"^:::(\w+)(?:\[(.*?)\])?\s*$", line)
        if opening and not quote:
            kind, title = opening.group(1).capitalize(), opening.group(2)
            out.append(f"> **{title or kind}**")
            quote = True
        elif quote and line.strip() == ":::":
            quote = False
        elif quote:
            out.append(f"> {line}" if line.strip() else ">")
        else:
            out.append(line)
    return out


def _prose(text: str, slug: str, slugs: set[str]) -> str:
    text = re.sub(r"^import .*\n", "", text, flags=re.M)
    text = "\n".join(_aside(text.split("\n")))
    text = text.replace(
        "<ConfigReference />",
        f"_The filterable key list is rendered on [herdr.dev]({UPSTREAM}/docs/{slug}/)._",
    )
    text = re.sub(r"<[A-Z]\w*\b[^>]*/>\n?", "", text)
    text = re.sub(
        r"<div[^>]*>(?:(?!</div>).)*?<img(?:(?!</div>).)*</div>",
        f"_Screenshots are on the [original page]({UPSTREAM}/docs/{slug}/)._",
        text,
        flags=re.S,
    )

    def docs_link(match: re.Match) -> str:
        target, anchor = match.group(1), match.group(2) or ""
        if target in slugs:
            return f"]({page_name(target)}{anchor})"
        return f"]({UPSTREAM}/docs/{target}/{anchor})"

    text = re.sub(r"\]\(/docs/([a-z0-9-]+)/?(#[^)\s]*)?\)", docs_link, text)
    text = re.sub(r"\]\(/docs/?\)", "](Documentation)", text)
    text = re.sub(r"\]\((/(?!/)[^)\s]*)\)", rf"]({UPSTREAM}\1)", text)
    return re.sub(r"`([^`\n]+)`", lambda m: f"`{rewrite_code(m.group(1))}`", text)


def convert(body: str, slug: str, slugs: set[str]) -> str:
    """Convert MDX to wiki markdown, leaving fenced code exactly as written."""
    out, prose, in_fence = [], [], False
    for line in body.split("\n"):
        if FENCE.match(line):
            if not in_fence and prose:
                out.append(_prose("\n".join(prose), slug, slugs))
                prose = []
            in_fence = not in_fence
            out.append(line)
        elif in_fence:
            out.append(rewrite_code(line))
        else:
            prose.append(line)
    if prose:
        out.append(_prose("\n".join(prose), slug, slugs))
    return "\n".join(out)


def _chrome() -> str:
    return (
        f'<a href="Home"><img src="{LOGO}" alt="moo" width="40" align="left" /></a> '
        '<strong>moo wiki</strong> · <a href="Home">Home</a> · <a href="Documentation">Documentation</a>'
    )


def _banner(slug: str) -> str:
    return (
        f"> **Adapted from [Herdr's documentation]({UPSTREAM}/docs/{slug}/)** "
        f"(Apache-2.0, © the Herdr authors; see the [LICENSE]({REPO}/blob/master/LICENSE)). "
        "Changed from the original: converted to wiki markdown, links rewritten, commands and "
        "config paths changed from `herdr` to `moo` where moo has the same command (checked against "
        "the moo CLI), and moo's additions included. Anything still saying `herdr` is upstream-only "
        "or names upstream itself; to install moo see [Install](Install)."
    )


# Pages whose subject differs between upstream and moo, so a reader needs more than the usual note.
SLUG_NOTES = {
    "install": (
        "> **This page installs upstream Herdr** (herdr.dev, Homebrew, mise, Nix) and describes its "
        "update channels. moo has its own installers and `moo update` downloads nothing: see [Install](Install)."
    ),
}


def render_page(slug: str, meta: dict[str, str], body: str, slugs: set[str]) -> str:
    title = meta.get("title", slug)
    parts = [MARKER, "", _chrome(), ""]
    if slug not in OWN:
        parts += [_banner(slug), ""]
    if slug in SLUG_NOTES:
        parts += [SLUG_NOTES[slug], ""]
    parts += [f"# {title}", ""]
    if meta.get("description"):
        parts += [f"_{meta['description']}_", ""]
    parts += [convert(body, slug, slugs).strip(), "", "---", ""]
    parts.append(f"_Source: `docs/next/website/src/content/docs/{slug}.mdx`. Edit that file; this page is regenerated._")
    return "\n".join(parts) + "\n"


def collect(docs: Path) -> dict[str, tuple[dict[str, str], str]]:
    pages = {}
    for path in sorted(docs.glob("*.mdx")):
        if path.stem not in SKIP:
            pages[path.stem] = split_frontmatter(path.read_text())
    return pages


def render_index(pages: dict[str, tuple[dict[str, str], str]]) -> str:
    rows = [
        f"- [{meta.get('title', slug)}]({page_name(slug)})"
        + (f": {meta['description']}" if meta.get("description") else "")
        for slug, (meta, _) in pages.items()
    ]
    return "\n".join(
        [MARKER, "", _chrome(), "", "# Documentation", "",
         "Generated from the repo's docs. Most pages are Herdr's documentation, adapted for moo; "
         "see the note at the top of each page.", "", *rows, ""]
    )


def render_sidebar(pages: dict, hand_written: list[str]) -> str:
    own = [f"- [{name.replace('-', ' ')}]({name})" for name in hand_written]
    ref = [f"- [{meta.get('title', slug)}]({page_name(slug)})" for slug, (meta, _) in pages.items()]
    return "\n".join([MARKER, "", "**[moo](Home)**", "", *own, "", "**Documentation**", "", *ref, ""])


def build(docs: Path, wiki: Path) -> dict[str, str]:
    """The generated files, by file name."""
    pages = collect(docs)
    slugs = set(pages)
    files = {
        f"{page_name(slug)}.md": render_page(slug, meta, body, slugs)
        for slug, (meta, body) in pages.items()
    }
    files["Documentation.md"] = render_index(pages)
    hand_written = sorted(
        path.stem
        for path in wiki.glob("*.md")
        if not path.name.startswith("_")
        and path.name not in files
        and MARKER not in path.read_text()
        and path.stem != "Home"
    )
    files["_Sidebar.md"] = render_sidebar(pages, hand_written)
    return files


def sync(docs: Path, wiki: Path, check: bool = False) -> list[str]:
    """Write (or, with check, only report) the changes; returns what changed."""
    files = build(docs, wiki)
    changes = []
    for name, content in files.items():
        target = wiki / name
        if target.exists():
            current = target.read_text()
            if MARKER not in current:
                raise SystemExit(f"refusing to overwrite hand-written page {name}")
            if current == content:
                continue
        changes.append(name)
        if not check:
            target.write_text(content)
    for stale in wiki.glob("*.md"):
        if stale.name not in files and MARKER in stale.read_text():
            changes.append(f"{stale.name} (removed)")
            if not check:
                stale.unlink()
    return changes


_WORD = re.compile(r"^[a-z][a-z0-9-]*$")


def moo_commands(text: str) -> set[tuple[str, ...]]:
    """The command words (`agent history`, `plugin action invoke`) of every `moo ...` in the code of `text`."""
    found = set()
    spans = []
    in_fence = False
    for line in text.split("\n"):
        if FENCE.match(line):
            in_fence = not in_fence
        elif in_fence:
            spans.append(line)
    spans += re.findall(r"`([^`\n]+)`", text)
    for span in spans:
        for match in re.finditer(r"(?:^\s*(?:\$\s+)?|\$\(\s*|\(\s*|[|;]\s*|&&\s*|\|\|\s*)moo((?:\s+\S+){0,4})", span):
            words = []
            for token in match.group(1).split():
                if not _WORD.match(token):
                    break
                words.append(token)
            found.add(tuple(words))
    return found


def verify(binary: str, wiki: Path) -> list[str]:
    """List the `moo ...` commands the generated pages show that moo does not have.

    Each command is walked word by word with `--help`: a word that is not a subcommand of a command
    that has subcommands is wrong, while the words after a leaf command are its arguments.
    """
    commands = set()
    for page in wiki.glob("Docs-*.md"):
        commands |= moo_commands(page.read_text())
    helps: dict[tuple[str, ...], str | None] = {}
    bad: set[str] = set()
    with tempfile.TemporaryDirectory() as home:
        env = {"PATH": os.environ.get("PATH", ""), "HOME": home}

        def help_of(words: tuple[str, ...]) -> str | None:
            if words not in helps:
                try:
                    result = subprocess.run(
                        [binary, *words, "--help"], capture_output=True, text=True, timeout=10, env=env, stdin=subprocess.DEVNULL
                    )
                    text = result.stdout + result.stderr
                    helps[words] = text if result.returncode == 0 and "sage" in text else None
                except (subprocess.TimeoutExpired, OSError):
                    helps[words] = None
            return helps[words]

        for words in sorted(commands):
            prefix: tuple[str, ...] = ()
            for word in words:
                found = help_of(prefix + (word,))
                # moo answers an unknown first word with its general help, so that is not a command
                if found is not None and not (prefix == () and found == help_of(())):
                    prefix += (word,)
                    continue
                parent = help_of(prefix)
                if prefix == () or (parent is not None and "Commands:" in parent):
                    bad.add("moo " + " ".join(prefix + (word,)))
                break
    return sorted(bad)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--wiki", required=True, type=Path, help="path to a checkout of the wiki")
    parser.add_argument("--docs", type=Path, default=DOCS)
    parser.add_argument("--check", action="store_true", help="exit 1 if the wiki is out of date")
    parser.add_argument("--verify", metavar="MOO", help="run every moo command the generated pages show through MOO --help; exit 1 if any fails")
    args = parser.parse_args(argv)
    if args.verify:
        bad = verify(args.verify, args.wiki)
        for command in bad:
            print(f"not a moo command: {command}")
        print(f"{len(bad)} commands moo does not have" if bad else "every command shown exists in moo")
        return 1 if bad else 0
    changes = sync(args.docs, args.wiki, args.check)
    for change in changes:
        print(("would change " if args.check else "wrote ") + change)
    if not changes:
        print("wiki is up to date")
    return 1 if (changes and args.check) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
